"""Turns tool/shapes.json (from vectorize.py) into lib/splash/logo_data.dart.

  python tool/vectorize.py tool/5l3b_logo.jpg tool/shapes.json
  python tool/gen_dart.py  tool/shapes.json lib/splash/logo_data.dart
"""
import json
import sys

import numpy as np

src, out = sys.argv[1], sys.argv[2]
data = json.load(open(src))
_, _, W, H = data['bbox']
ball = data['ball']


def fmt(v):
    s = f'{v:.1f}'
    return s[:-2] if s.endswith('.0') else s


def centerline(contour, samples=28):
    """(x, y) middle of a thin shape, at evenly spaced x."""
    pts = np.array(list(zip(contour[0::2], contour[1::2])))
    xs = np.linspace(pts[:, 0].min() + 1, pts[:, 0].max() - 1, samples)
    res = []
    n = len(pts)
    for x in xs:
        ys = []
        for i in range(n):
            (x0, y0), (x1, y1) = pts[i], pts[(i + 1) % n]
            if (x0 <= x < x1) or (x1 <= x < x0):
                ys.append(y0 + (x - x0) * (y1 - y0) / (x1 - x0))
        if len(ys) >= 2:
            res.append((x, (min(ys) + max(ys)) / 2, max(ys) - min(ys)))
    return res


lines = [
    '// dart format off',
    '// GENERATED by tool/gen_dart.py from tool/shapes.json. Do not edit by hand.',
    '//',
    '// The 5L3B logo as polygons, in the units of the original 1600px picture,',
    '// with (0, 0) at the top-left corner of the logo.',
    '',
    '/// One animated piece of the logo: all the outlines of one color.',
    'class LogoPartData {',
    '  const LogoPartData(this.name, this.color, this.contours);',
    '',
    '  final String name;',
    '',
    '  /// 0xAARRGGBB.',
    '  final int color;',
    '',
    '  /// Closed outlines, each one `[x0, y0, x1, y1, ...]`. Holes are outlines',
    '  /// too: the pieces are filled with the even-odd rule.',
    '  final List<List<double>> contours;',
    '}',
    '',
    f'const double kLogoWidth = {W};',
    f'const double kLogoHeight = {H};',
    '',
    '/// The circle of the ball.',
    f"const double kBallCx = {fmt(ball['cx'])};",
    f"const double kBallCy = {fmt(ball['cy'])};",
    f"const double kBallRadius = {fmt(ball['r'])};",
    '',
    'const List<LogoPartData> kLogoParts = [',
]
swoosh = None
for part in data['parts']:
    color = '0xFF' + part['color']
    lines.append(f"  LogoPartData('{part['name']}', {color}, [")
    for c in part['contours']:
        lines.append('    [' + ', '.join(fmt(v) for v in c) + '],')
    lines.append('  ]),')
    if part['name'] == 'swoosh':
        swoosh = max(part['contours'], key=len)
lines.append('];')
lines.append('')

# The stroke is thin: the glow at its tip needs to know where its middle is.
mid = centerline(swoosh)
lines.append('/// Middle line of the stroke that shoots out of the 5: `[x, y, thickness, ...]`.')
lines.append('const List<double> kSwooshMiddle = [')
for x, y, t in mid:
    lines.append(f'  {fmt(x)}, {fmt(y)}, {fmt(t)},')
lines.append('];')
open(out, 'w').write('\n'.join(lines) + '\n')
print('wrote', out, len(lines), 'lines')
